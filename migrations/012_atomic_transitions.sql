-- 012 (ДЕМО 2.0, Етап 2): атомарні переходи заявок і ручних закриттів.
--
-- Кожна публічна transition_* функція виконується PostgreSQL як одна
-- транзакція: перевіряє поточний стан, блокує рядок, оновлює об'єкт,
-- створює версію нового стану та пише журнал. Очікувані конфлікти
-- повертаються як JSON із success=false; неочікувана SQL-помилка відкочує все.

begin;

-- Відкликання стає м'яким: заявка зникає з робочих вибірок, але рядок,
-- версії та журнал не видаляються каскадно.
alter table public.monitoring_requests
    drop constraint if exists chk_approval_status;

alter table public.monitoring_requests
    add constraint chk_approval_status check (approval_status in (
        'Очікує погодження',
        'Очікує: Керівник ССП',
        'Очікує: Керівник управління',
        'Очікує: Заступник керівника ССП',
        'Очікує: Супер-адмін',
        'Повернуто на доопрацювання',
        'Погоджено',
        'Відкликано'
    ));

drop index if exists public.uq_measure_request_per_period;
create unique index uq_measure_request_per_period
    on public.monitoring_requests (strat_code, year, quarter)
    where object_kind = 'measure'
      and approval_status <> 'Відкликано';

-- Версії запитів на ручне закриття.
create table if not exists public.closeout_request_versions (
    id                  bigint generated by default as identity primary key,
    closeout_request_id bigint not null
        references public.closeout_requests(id) on delete cascade,
    version_number      integer not null,
    snapshot_data       jsonb not null,
    created_at          timestamptz not null default now(),
    created_by          text not null default 'system',
    unique (closeout_request_id, version_number)
);

create index if not exists idx_closeout_request_versions_request
    on public.closeout_request_versions (closeout_request_id, version_number);

alter table public.closeout_request_versions enable row level security;
drop policy if exists closeout_versions_all_select on public.closeout_request_versions;
drop policy if exists closeout_versions_all_insert on public.closeout_request_versions;
create policy closeout_versions_all_select
    on public.closeout_request_versions for select using (true);
create policy closeout_versions_all_insert
    on public.closeout_request_versions for insert with check (true);

grant select, insert on public.closeout_request_versions
    to anon, authenticated, service_role;
grant usage, select on sequence public.closeout_request_versions_id_seq
    to anon, authenticated, service_role;

create schema if not exists monitoring_internal;
grant usage on schema monitoring_internal to anon, authenticated, service_role;

create or replace function monitoring_internal.actor_label(p_actor jsonb)
returns text
language sql
immutable
security invoker
set search_path = pg_catalog
as $$
    select concat_ws(
        ' · ',
        nullif(btrim(coalesce(p_actor->>'role', '')), ''),
        nullif(btrim(coalesce(p_actor->>'name', '')), ''),
        case
            when nullif(btrim(coalesce(p_actor->>'email', '')), '') is not null
            then '<' || lower(btrim(p_actor->>'email')) || '>'
            else null
        end
    );
$$;

create or replace function monitoring_internal.snapshot_request(
    p_request_id bigint,
    p_created_by text
)
returns integer
language plpgsql
security invoker
set search_path = public, pg_catalog
as $$
declare
    v_version integer;
begin
    select coalesce(max(version_number), 0) + 1
      into v_version
      from public.monitoring_request_versions
     where request_id = p_request_id;

    insert into public.monitoring_request_versions (
        request_id, version_number, year, quarter, department,
        responsible_person, phone, email, strat_code, status,
        progress_text, numeric_value, value_text, risks, file_names,
        file_urls, approval_status, admin_comment, start_date, end_date,
        created_by, npa_link, approval_chain, chain_stage, scheme_label,
        object_kind, object_name, indicator_name, as_of_date
    )
    select
        r.id, v_version, r.year, r.quarter, r.department,
        r.responsible_person, r.phone, r.email, r.strat_code, r.status,
        r.progress_text, r.numeric_value, r.value_text, r.risks, r.file_names,
        r.file_urls, r.approval_status, r.admin_comment, r.start_date, r.end_date,
        coalesce(nullif(btrim(p_created_by), ''), 'system'),
        r.npa_link, r.approval_chain, r.chain_stage, r.scheme_label,
        r.object_kind, r.object_name, r.indicator_name, r.as_of_date
      from public.monitoring_requests r
     where r.id = p_request_id;

    if not found then
        raise exception 'Заявку % не знайдено під час створення версії.', p_request_id;
    end if;

    return v_version;
end;
$$;

create or replace function monitoring_internal.snapshot_closeout(
    p_closeout_id bigint,
    p_created_by text
)
returns integer
language plpgsql
security invoker
set search_path = public, pg_catalog
as $$
declare
    v_version integer;
begin
    select coalesce(max(version_number), 0) + 1
      into v_version
      from public.closeout_request_versions
     where closeout_request_id = p_closeout_id;

    insert into public.closeout_request_versions (
        closeout_request_id, version_number, snapshot_data, created_by
    )
    select
        c.id,
        v_version,
        to_jsonb(c),
        coalesce(nullif(btrim(p_created_by), ''), 'system')
      from public.closeout_requests c
     where c.id = p_closeout_id;

    if not found then
        raise exception 'Запит на ручне закриття % не знайдено під час створення версії.', p_closeout_id;
    end if;

    return v_version;
end;
$$;

create or replace function monitoring_internal.write_log(
    p_request_id bigint,
    p_action text,
    p_old_status text,
    p_new_status text,
    p_comment text,
    p_actor jsonb,
    p_strat_code text,
    p_related_table text,
    p_related_key text,
    p_details jsonb default '{}'::jsonb
)
returns bigint
language plpgsql
security invoker
set search_path = public, monitoring_internal, pg_catalog
as $$
declare
    v_log_id bigint;
    v_actor_email text := lower(btrim(coalesce(p_actor->>'email', '')));
    v_actor_name text := btrim(coalesce(p_actor->>'name', ''));
    v_actor_role text := btrim(coalesce(p_actor->>'role', ''));
begin
    insert into public.monitoring_logs (
        request_id, action, old_status, new_status, admin_comment,
        changed_by, changed_at, actor_email, actor_name, actor_role,
        strat_code, related_table, related_key, payload_json
    ) values (
        p_request_id,
        coalesce(p_action, ''),
        coalesce(p_old_status, ''),
        coalesce(p_new_status, ''),
        coalesce(p_comment, ''),
        monitoring_internal.actor_label(p_actor),
        now(),
        v_actor_email,
        v_actor_name,
        v_actor_role,
        coalesce(p_strat_code, ''),
        coalesce(nullif(p_related_table, ''), 'monitoring_requests'),
        coalesce(p_related_key, ''),
        coalesce(p_details, '{}'::jsonb)::text
    )
    returning id into v_log_id;

    return v_log_id;
end;
$$;

-- Погодження поточного кроку, передавання наступній ланці або остаточне
-- погодження з одночасним final_locked.
create or replace function public.transition_approve_request_step(
    p_request_id bigint,
    p_expected_status text,
    p_expected_chain_stage integer,
    p_new_status text,
    p_new_chain_stage integer,
    p_approval_chain text,
    p_comment text,
    p_action text,
    p_actor jsonb,
    p_created_by text
)
returns jsonb
language plpgsql
security invoker
set search_path = public, monitoring_internal, pg_catalog
as $$
declare
    v_row public.monitoring_requests%rowtype;
    v_version integer;
    v_allowed text[] := array[
        'Очікує погодження',
        'Очікує: Керівник ССП',
        'Очікує: Керівник управління',
        'Очікує: Заступник керівника ССП',
        'Очікує: Супер-адмін',
        'Погоджено'
    ];
begin
    select * into v_row
      from public.monitoring_requests
     where id = p_request_id
     for update;

    if not found then
        return jsonb_build_object('success', false, 'code', 'not_found',
                                  'message', 'Заявку не знайдено.');
    end if;
    if v_row.final_locked then
        return jsonb_build_object('success', false, 'code', 'already_final_locked',
                                  'message', 'Заявку вже остаточно погоджено.');
    end if;
    if v_row.approval_status is distinct from p_expected_status
       or coalesce(v_row.chain_stage, 0) is distinct from coalesce(p_expected_chain_stage, 0)
    then
        return jsonb_build_object(
            'success', false,
            'code', 'state_changed',
            'message', 'Перехід недопустимий: заявку вже опрацювала інша ланка.',
            'current_status', v_row.approval_status,
            'current_chain_stage', coalesce(v_row.chain_stage, 0)
        );
    end if;
    if not (p_new_status = any(v_allowed)) then
        return jsonb_build_object('success', false, 'code', 'invalid_target_status',
                                  'message', 'Задано недопустимий новий статус.');
    end if;
    if coalesce(p_new_chain_stage, 0) < coalesce(v_row.chain_stage, 0) then
        return jsonb_build_object('success', false, 'code', 'invalid_stage_direction',
                                  'message', 'Погодження не може повернути заявку на попередню ланку.');
    end if;

    update public.monitoring_requests
       set approval_status = p_new_status,
           chain_stage = coalesce(p_new_chain_stage, chain_stage),
           approval_chain = coalesce(p_approval_chain, approval_chain),
           admin_comment = coalesce(p_comment, ''),
           final_locked = case when p_new_status = 'Погоджено' then true else final_locked end,
           final_locked_at = case
               when p_new_status = 'Погоджено' then coalesce(final_locked_at, now())
               else final_locked_at
           end
     where id = p_request_id;

    v_version := monitoring_internal.snapshot_request(
        p_request_id,
        coalesce(p_created_by, 'Погодження')
    );

    perform monitoring_internal.write_log(
        p_request_id, p_action, v_row.approval_status, p_new_status,
        p_comment, p_actor, v_row.strat_code, 'monitoring_requests',
        p_request_id::text,
        jsonb_build_object('version_number', v_version)
    );

    return jsonb_build_object(
        'success', true, 'code', 'ok', 'message', 'Перехід виконано.',
        'request_id', p_request_id, 'new_status', p_new_status,
        'new_chain_stage', p_new_chain_stage,
        'final_locked', p_new_status = 'Погоджено',
        'version_number', v_version
    );
end;
$$;

