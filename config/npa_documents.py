def normalize_for_match(text: str) -> str:
    """Нормалізація назви для звірки довідника з матрицею."""
    import re as _re
    t = str(text or "").replace("\u00a0", " ").replace("’", "'").replace("`", "'")
    t = t.replace("«", "\"").replace("»", "\"")
    t = _re.sub(r"^[\s\"'*]*\d*[\.)\-\s]*", "", t)   # зірочки, номери, лапки на початку
    t = t.strip(" \t\n\r\"'.,;:")
    t = _re.sub(r"[—–]", "-", t)                        # уніфікація тире
    t = _re.sub(r"\s+", " ", t)
    return t.lower()
