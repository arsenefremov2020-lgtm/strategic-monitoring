$$;

-- Створення запиту на ручне закриття. Для супер-адміна початковий
-- статус може бути одразу «Підтверджено»; insert, версія і журнал атомарні.
create or replace function public.transition_create_closeout(
    p_payload jsonb,
    p_actor jsonb
)
returns jsonb
language plpgsql
security invoker
set search_path = public, monitoring_internal, pg_catalog
as $$
declare
    v_row public.closeout_requests%rowtype;
    v_version integer;
    v_status text := coalesce(nullif(btrim(p_payload->>'approval_status'), ''),
                              'Очікує підтвердження');
begin
    if nullif(btrim(coalesce(p_payload->>'strat_code', '')), '') is null then
        return jsonb_build_object('success', false, 'code', 'strat_code_required',
                                  'message', 'Не зазначено код заходу.');
    end if;
    if nullif(btrim(coalesce(p_payload->>'reason', '')), '') is null then
        return jsonb_build_object('success', false, 'code', 'reason_required',
                                  'message', 'Підстава ручного закриття обов’язкова.');
    end if;
    if v_status not in ('Очікує підтвердження', 'Підтверджено') then
        return jsonb_build_object('success', false, 'code', 'invalid_initial_status',
                                  'message', 'Недопустимий початковий статус ручного закриття.');
    end if;

    insert into public.closeout_requests (
        strat_code, period_year, period_quarter, admin_id, admin_email,
        reason, evidence_note, approval_status, superadmin_id, decided_at,
        npa_links, scope, head_status, head_email,
        assigned_superadmin_email, assigned_superadmin_name,
        senior_superadmin_email, senior_superadmin_name, routing_note
    ) values (
        btrim(p_payload->>'strat_code'),
        nullif(p_payload->>'period_year', '')::smallint,
        nullif(p_payload->>'period_quarter', '')::smallint,
        coalesce(p_payload->>'admin_id', ''),
        lower(btrim(coalesce(p_payload->>'admin_email', ''))),
        btrim(p_payload->>'reason'),
        coalesce(p_payload->>'evidence_note', ''),
        v_status,
        case when v_status = 'Підтверджено'
             then coalesce(nullif(p_payload->>'superadmin_id', ''),
                           p_actor->>'email', p_actor->>'name', '')
             else nullif(p_payload->>'superadmin_id', '') end,
        case when v_status = 'Підтверджено' then now() else null end,
        coalesce(p_payload->>'npa_links', ''),
        coalesce(nullif(p_payload->>'scope', ''), 'Квартал'),
        case when v_status = 'Підтверджено'
             then coalesce(nullif(p_payload->>'head_status', ''), 'Очікує реакції')
             else nullif(p_payload->>'head_status', '') end,
        nullif(p_payload->>'head_email', ''),
        nullif(p_payload->>'assigned_superadmin_email', ''),
        nullif(p_payload->>'assigned_superadmin_name', ''),
        nullif(p_payload->>'senior_superadmin_email', ''),
        nullif(p_payload->>'senior_superadmin_name', ''),
        nullif(p_payload->>'routing_note', '')
    ) returning * into v_row;

    v_version := monitoring_internal.snapshot_closeout(
        v_row.id, 'Ручне закриття / створення'
    );

    perform monitoring_internal.write_log(
        null,
        'Ручне закриття заходу',
        '',
        v_status,
        v_row.reason,
        p_actor,
        v_row.strat_code,
        'closeout_requests',
        v_row.id::text,
        jsonb_build_object(
            'version_number', v_version,
            'scope', v_row.scope,
            'year', v_row.period_year,
            'quarter', v_row.period_quarter
        )
    );

    return jsonb_build_object(
        'success', true, 'code', 'ok',
        'message', case when v_status = 'Підтверджено'
                        then 'Захід закрито вручну.'
                        else 'Запит на ручне закриття створено.' end,
        'closeout_id', v_row.id,
        'new_status', v_status,
        'version_number', v_version
    );
end;
$$;

-- Рішення супер-адміна щодо запиту на ручне закриття.
create or replace function public.transition_decide_closeout(
    p_closeout_id bigint,
    p_expected_status text,
    p_new_status text,
    p_decision_comment text,
    p_head_email text,
    p_actor jsonb
)
returns jsonb
language plpgsql
security invoker
set search_path = public, monitoring_internal, pg_catalog
as $$
declare
    v_row public.closeout_requests%rowtype;
    v_version integer;
    v_actor_id text := coalesce(p_actor->>'email', p_actor->>'name', '');
begin
    if p_new_status not in ('Підтверджено', 'Відхилено') then
        return jsonb_build_object('success', false, 'code', 'invalid_target_status',
                                  'message', 'Недопустиме рішення щодо ручного закриття.');
    end if;

    select * into v_row
      from public.closeout_requests
     where id = p_closeout_id
     for update;

    if not found then
        return jsonb_build_object('success', false, 'code', 'not_found',
                                  'message', 'Запит на ручне закриття не знайдено.');
    end if;
    if v_row.approval_status is distinct from p_expected_status then
        return jsonb_build_object(
            'success', false, 'code', 'state_changed',
            'message', 'Перехід недопустимий: цей запит уже розглянуто.',
            'current_status', v_row.approval_status
        );
    end if;

    update public.closeout_requests
       set approval_status = p_new_status,
           superadmin_id = v_actor_id,
           decided_at = now(),
           decision_comment = coalesce(p_decision_comment, ''),
           head_status = case
               when p_new_status = 'Підтверджено' then 'Очікує реакції'
               else head_status
           end,
           head_email = case
               when p_new_status = 'Підтверджено'
               then coalesce(nullif(btrim(p_head_email), ''), head_email)
               else head_email
           end
     where id = p_closeout_id;

    v_version := monitoring_internal.snapshot_closeout(
        p_closeout_id, 'Ручне закриття / після рішення'
    );

    perform monitoring_internal.write_log(
        null,
        'Закриття заходу: ' || p_new_status,
        v_row.approval_status,
        p_new_status,
        p_decision_comment,
        p_actor,
        v_row.strat_code,
        'closeout_requests',
        p_closeout_id::text,
        jsonb_build_object('version_number', v_version)
    );

    return jsonb_build_object(
        'success', true, 'code', 'ok', 'message', 'Рішення зафіксовано.',
        'closeout_id', p_closeout_id, 'new_status', p_new_status,
        'version_number', v_version
    );
end;
$$;

-- Окрема атомарна операція final_locked для службових сценаріїв.
create or replace function public.transition_set_final_locked(
    p_request_id bigint,
    p_expected_status text,
    p_comment text,
    p_action text,
    p_actor jsonb
)
returns jsonb
language plpgsql
security invoker
set search_path = public, monitoring_internal, pg_catalog
as $$
declare
    v_row public.monitoring_requests%rowtype;
    v_version integer;
begin
    select * into v_row
      from public.monitoring_requests
     where id = p_request_id
     for update;

    if not found then
        return jsonb_build_object('success', false, 'code', 'not_found',
                                  'message', 'Заявку не знайдено.');
    end if;
    if v_row.final_locked then
        return jsonb_build_object('success', false, 'code', 'already_final_locked',
                                  'message', 'Заявку вже остаточно закрито.');
    end if;
    if v_row.approval_status is distinct from p_expected_status
       or v_row.approval_status <> 'Погоджено'
    then
        return jsonb_build_object('success', false, 'code', 'invalid_state',
                                  'message', 'final_locked можна встановити лише погодженій заявці.');
    end if;

    update public.monitoring_requests
       set final_locked = true,
           final_locked_at = coalesce(final_locked_at, now()),
           admin_comment = coalesce(nullif(p_comment, ''), admin_comment)
     where id = p_request_id;

    v_version := monitoring_internal.snapshot_request(
        p_request_id, 'Система / final_locked'
    );

    perform monitoring_internal.write_log(
        p_request_id, coalesce(nullif(p_action, ''), 'Остаточне закриття заявки'),
        v_row.approval_status, v_row.approval_status, p_comment, p_actor,
        v_row.strat_code, 'monitoring_requests', p_request_id::text,
        jsonb_build_object('version_number', v_version)
    );

    return jsonb_build_object(
        'success', true, 'code', 'ok', 'message', 'Заявку остаточно закрито.',
        'request_id', p_request_id, 'final_locked', true,
        'version_number', v_version
    );
end;
$$;

-- Коригування даних уже остаточно закритої заявки супер-адміном.
create or replace function public.transition_correct_locked_request(
    p_request_id bigint,
    p_updates jsonb,
    p_reason text,
    p_actor jsonb
)
returns jsonb
language plpgsql
security invoker
set search_path = public, monitoring_internal, pg_catalog
as $$
declare
    v_row public.monitoring_requests%rowtype;
    v_before integer;
    v_after integer;
    v_bad_fields text[];
    v_allowed_fields text[] := array[
        'status', 'numeric_value', 'value_text', 'progress_text',
        'risks', 'npa_link'
    ];
begin
    if nullif(btrim(coalesce(p_reason, '')), '') is null then
        return jsonb_build_object('success', false, 'code', 'reason_required',
                                  'message', 'Для коригування обов’язкова підстава.');
    end if;

    select array_agg(keys.key order by keys.key)
      into v_bad_fields
      from jsonb_object_keys(coalesce(p_updates, '{}'::jsonb)) as keys(key)
     where not (keys.key = any(v_allowed_fields));

    if v_bad_fields is not null then
        return jsonb_build_object(
            'success', false, 'code', 'invalid_fields',
            'message', 'Спроба змінити заборонені поля закритої заявки.',
            'fields', to_jsonb(v_bad_fields)
        );
    end if;

    select * into v_row
      from public.monitoring_requests
     where id = p_request_id
     for update;

    if not found then
        return jsonb_build_object('success', false, 'code', 'not_found',
                                  'message', 'Заявку не знайдено.');
    end if;
    if not v_row.final_locked or v_row.approval_status <> 'Погоджено' then
        return jsonb_build_object('success', false, 'code', 'not_final_locked',
                                  'message', 'Коригування доступне лише для остаточно погодженої заявки.');
    end if;

    v_before := monitoring_internal.snapshot_request(
        p_request_id, 'Супер-адмін / до коригування'
    );

    update public.monitoring_requests
       set status = case
               when p_updates ? 'status' then nullif(p_updates->>'status', '')
               else status
           end,
           numeric_value = case
               when p_updates ? 'numeric_value'
               then nullif(p_updates->>'numeric_value', '')::numeric
               else numeric_value
           end,
           value_text = case
               when p_updates ? 'value_text' then nullif(p_updates->>'value_text', '')
               else value_text
           end,
           progress_text = case
               when p_updates ? 'progress_text' then coalesce(p_updates->>'progress_text', '')
               else progress_text
           end,
           risks = case
               when p_updates ? 'risks' then coalesce(p_updates->>'risks', '')
               else risks
           end,
           npa_link = case
               when p_updates ? 'npa_link' then coalesce(p_updates->>'npa_link', '')
               else npa_link
           end,
           admin_comment = 'Коригування супер-адміном після закриття: ' || btrim(p_reason)
     where id = p_request_id;

    v_after := monitoring_internal.snapshot_request(
        p_request_id, 'Супер-адмін / коригування після закриття'
    );

    perform monitoring_internal.write_log(
        p_request_id,
        'Коригування даних супер-адміном після закриття: версія '
            || v_before || ' → ' || v_after,
        v_row.approval_status,
        v_row.approval_status,
        'Підстава: ' || btrim(p_reason),
        p_actor,
        v_row.strat_code,
        'monitoring_requests',
        p_request_id::text,
        jsonb_build_object('version_before', v_before, 'version_after', v_after)
    );

    return jsonb_build_object(
        'success', true, 'code', 'ok', 'message', 'Дані скориговано.',
        'request_id', p_request_id,
        'version_before', v_before, 'version_after', v_after
    );
end;
$$;

