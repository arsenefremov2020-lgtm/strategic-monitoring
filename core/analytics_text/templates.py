def phrase_pool(category: str, *tags: str) -> list[PhraseVariant]:
    values = PHRASE_LIBRARY.get(category, [])
    wanted = set(tags)
    if not wanted:
        return list(values)
    filtered = [item for item in values if not item.suitable_for or wanted.intersection(item.suitable_for)]
    return filtered or list(values)


def phrase_count() -> int:
    return sum(len(items) for items in PHRASE_LIBRARY.values())
