from __future__ import annotations

from collections import defaultdict

from .models import PhraseVariant


PHRASE_LIBRARY: dict[str, list[PhraseVariant]] = defaultdict(list)


def _add(category: str, tag: str, texts: list[str]) -> None:
    start = len(PHRASE_LIBRARY[category]) + 1
    for offset, text in enumerate(texts):
        PHRASE_LIBRARY[category].append(
            PhraseVariant(
                id=f"{category}_{start + offset:03d}",
                template=text,
                suitable_for=(tag,),
            )
        )


