# -------------------------------------------------
# Службова функція для шапки сторінки
# -------------------------------------------------

def render_page_header(title: str, description: str | None = None) -> None:
    """
    Виводить заголовок сторінки.
    """

    st.title(title)

    if description:
        st.caption(description)


# -------------------------------------------------
# Сторінка: app
# -------------------------------------------------

def render_app_page() -> None:
    """
    Публічна головна сторінка.

    Доступ:
    - ССП
    - керівник ССП
    - адміністратор
    - супер-адмін
    - користувач без реєстрації
    """

    if not require_page_access("app"):
        return

    render_page_header(
        "app",
        "Головна сторінка системи моніторингу стратегічного плану."
    )

    st.info(
        "Тут має бути чинний вміст головної сторінки `app`. "
        "На наступному кроці сюди переноситься поточний код головної сторінки."
    )


