def render_my_cabinet_page() -> None:
    """
    Мій кабінет керівника ССП.

    Доступ:
    - керівник ССП
    """

    if not require_page_access("Мій кабінет"):
        return

    user = get_current_user()

    render_page_header(
        "Мій кабінет",
        "Кабінет керівника самостійного структурного підрозділу."
    )

    if user.get("ssp"):
        st.success(f"ССП: {user.get('ssp')}")

    st.info(
        "Тут має бути код кабінету керівника ССП."
    )


