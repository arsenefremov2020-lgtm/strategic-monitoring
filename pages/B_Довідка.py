import streamlit as st

from core.page_setup import page_setup, render_footer


page_setup("Довідка", page_name="Довідка")

st.markdown('<div class="section-title">Довідка</div>', unsafe_allow_html=True)
st.warning("ТЕСТОВИЙ РЕЖИМ · Текст довідки потребує фінального затвердження замовником.")
st.caption("Коротка пам’ятка для користувачів системи моніторингу стратегічного плану.")

with st.expander("Як увійти в систему", expanded=True):
    st.markdown(
        """
1. Відкрийте систему та введіть свою робочу електронну адресу і пароль.
2. Після успішного входу система запам’ятає вас до кінця поточного дня.
3. Якщо протягом години немає активності, система завершить сесію — потрібно увійти повторно.
4. Для завершення роботи натисніть «Вийти з системи».
"""
    )

with st.expander("Відповідальна особа від ССП: як подати звіт"):
    st.markdown(
        """
1. Відкрийте «Моніторинг виконання».
2. Оберіть звітний рік і квартал та знайдіть потрібний захід.
3. Заповніть статус виконання, фактичне значення, опис прогресу, ризики та посилання на підтвердні матеріали.
4. Перевірте схему погодження та подайте заявку.
5. Після подання дочекайтеся зеленого повідомлення про успішне подання.
6. Свої заявки переглядайте у вкладці «Мої заявки».

Незаповнені зміни автоматично зберігаються як чернетка. Після оновлення сторінки її можна відновити або відхилити.
"""
    )

with st.expander("Керівник ССП / керівник управління / заступник керівника ССП: як погодити"):
    st.markdown(
        """
1. Відкрийте «Мій кабінет».
2. Перегляньте заявки, які очікують саме вашого рішення.
3. Перевірте подані фактичні дані та пояснення.
4. Для погодження натисніть відповідну кнопку — заявка перейде на наступну ланку.
5. Для повернення обов’язково зазначте зрозумілий коментар із причиною.
"""
    )

with st.expander("Що робити, якщо заявку повернуто"):
    st.markdown(
        """
1. Відповідальна особа від ССП відкриває повернуту заявку у «Моїх заявках».
2. Ознайомлюється з коментарем погоджувача.
3. Виправляє фактичні дані або пояснення.
4. Повторно подає заявку.
5. Якщо за час редагування заявку вже змінив інший користувач, система не затре нові дані та збереже ваші зміни в чернетці.
"""
    )

with st.expander("Адміністратор і супер-адмін"):
    st.markdown(
        """
**Адміністратор** працює у вкладці «Адміністрування»: перевіряє заявки, погоджує або повертає їх, а також може створювати запити на ручне закриття заходів.

**Супер-адмін** має додатковий доступ до оцінки МіО, журналу, аналітики, остаточного рішення щодо ручних закриттів, коригування остаточно закритих заявок та створення архівних знімків.
"""
    )

with st.expander("Архів"):
    st.markdown(
        """
Архівний знімок — це незмінна фотографія системи на конкретний момент часу. Після створення його не можна редагувати або видалити. Якщо в живих даних виявлена помилка, спочатку виправляють живі дані, а потім створюють новий знімок-заміна з поясненням причини.
"""
    )

st.info(
    "В разі технічних питань чи пропозицій, звертайтеся за електронною адресою: "
    "a.efremov@me.gov.ua"
)

render_footer()
